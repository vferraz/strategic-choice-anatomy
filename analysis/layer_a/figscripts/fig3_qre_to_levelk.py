def _compact_decimal(x: float) -> str:
    s = f"{x:.2f}"
    return s.replace("0.", ".").replace("-0.", "-.")


def _ols_intercept_slope(x: np.ndarray, y: np.ndarray) -> tuple[float, float]:
    X = np.column_stack([np.ones(len(x)), x])
    beta = np.linalg.lstsq(X, y, rcond=None)[0]
    return float(beta[0]), float(beta[1])


def _partial_complexity(x_complexity: np.ndarray, x_delta: np.ndarray,
                        y: np.ndarray) -> tuple[float, float]:
    """Return the complexity coefficient and partial Pearson correlation.

    The coefficient is from ``y ~ 1 + delta1c + complexity``.  The partial
    correlation is Pearson's r between the residuals from regressing ``y`` and
    ``complexity`` separately on ``1 + delta1c``.
    """
    X = np.column_stack([np.ones(len(y)), x_delta, x_complexity])
    beta = np.linalg.lstsq(X, y, rcond=None)[0]
    base = np.column_stack([np.ones(len(y)), x_delta])
    y_resid = y - base @ np.linalg.lstsq(base, y, rcond=None)[0]
    x_resid = x_complexity - base @ np.linalg.lstsq(base, x_complexity, rcond=None)[0]
    r = np.nan
    if np.std(x_resid) > 1e-10 and np.std(y_resid) > 1e-10:
        r = float(np.corrcoef(x_resid, y_resid)[0, 1])
    return float(beta[2]), r


def _clean_xy(d: pd.DataFrame) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    x = d["complexity_score"].to_numpy(float)
    y = d["s"].to_numpy(float) / d["n"].to_numpy(float)
    z = d["delta1c_unif"].to_numpy(float)
    ok = np.isfinite(x) & np.isfinite(y) & np.isfinite(z)
    return x[ok], y[ok], z[ok]


def _bootstrap_response(x: np.ndarray, y: np.ndarray, z: np.ndarray) -> dict[str, float]:
    rng = np.random.default_rng(SEED)
    slope_vals, rho_vals, partial_slope_vals, partial_r_vals = [], [], [], []
    n = len(y)
    for _ in range(N_BOOT):
        idx = rng.integers(0, n, size=n)
        xb, yb, zb = x[idx], y[idx], z[idx]
        if np.std(xb) <= 1e-10 or np.std(yb) <= 1e-10:
            continue
        _, slope = _ols_intercept_slope(xb, yb)
        rho = spearmanr(xb, yb).correlation
        ps, pr = _partial_complexity(xb, zb, yb)
        slope_vals.append(slope)
        rho_vals.append(rho)
        partial_slope_vals.append(ps)
        partial_r_vals.append(pr)

    def ci(vals):
        vals = np.asarray(vals, float)
        vals = vals[np.isfinite(vals)]
        if vals.size == 0:
            return np.nan, np.nan
        return float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))

    slo, shi = ci(slope_vals)
    rlo, rhi = ci(rho_vals)
    pslo, pshi = ci(partial_slope_vals)
    prlo, prhi = ci(partial_r_vals)
    return {
        "slope_ci_lo": slo, "slope_ci_hi": shi,
        "rho_ci_lo": rlo, "rho_ci_hi": rhi,
        "partial_slope_ci_lo": pslo, "partial_slope_ci_hi": pshi,
        "partial_r_ci_lo": prlo, "partial_r_ci_hi": prhi,
    }


def build_complexity_response(agent_games: dict[str, pd.DataFrame]) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    summary_rows = []
    bin_rows = []
    partial_rows = []
    for ag in AGENTS:
        d = agent_games[ag].copy()
        x, y, z = _clean_xy(d)
        intercept, slope = _ols_intercept_slope(x, y)
        rho = float(spearmanr(x, y).correlation)
        partial_slope, partial_r = _partial_complexity(x, z, y)
        boot = _bootstrap_response(x, y, z)
        summary_rows.append({
            "agent": ag, "display": DISPLAY[ag], "subset": "all",
            "n_games": int(len(y)), "intercept": intercept, "slope": slope,
            "spearman_rho": rho, "partial_slope_ctrl_delta1c": partial_slope,
            "partial_r_ctrl_delta1c": partial_r, **boot,
        })

        plot_df = pd.DataFrame({"complexity_score": x, "p_canon": y})
        plot_df["bin"] = pd.qcut(plot_df["complexity_score"], q=5, labels=False, duplicates="drop")
        for b, sub in plot_df.groupby("bin", sort=True):
            bin_rows.append({
                "agent": ag, "display": DISPLAY[ag], "bin": int(b),
                "n_games": int(len(sub)),
                "complexity_mean": float(sub["complexity_score"].mean()),
                "p_canon_mean": float(sub["p_canon"].mean()),
                "p_canon_se": float(sub["p_canon"].std(ddof=1) / math.sqrt(len(sub))) if len(sub) > 1 else np.nan,
            })

        for subset, families in {
            "all": None,
            "dominance_solvable": {"DD", "OD1", "OD2"},
        }.items():
            sd = d if families is None else d[d["family"].isin(families)]
            sx, sy, sz = _clean_xy(sd)
            ps, pr = _partial_complexity(sx, sz, sy)
            sb = _bootstrap_response(sx, sy, sz)
            partial_rows.append({
                "agent": ag, "display": DISPLAY[ag], "subset": subset,
                "n_games": int(len(sy)),
                "partial_slope_ctrl_delta1c": ps,
                "partial_slope_ci_lo": sb["partial_slope_ci_lo"],
                "partial_slope_ci_hi": sb["partial_slope_ci_hi"],
                "partial_r_ctrl_delta1c": pr,
                "partial_r_ci_lo": sb["partial_r_ci_lo"],
                "partial_r_ci_hi": sb["partial_r_ci_hi"],
                "spearman_rho_raw": float(spearmanr(sx, sy).correlation),
                "spearman_rho_raw_ci_lo": sb["rho_ci_lo"],
                "spearman_rho_raw_ci_hi": sb["rho_ci_hi"],
            })

    summary = pd.DataFrame(summary_rows)
    bins = pd.DataFrame(bin_rows)
    partial = pd.DataFrame(partial_rows)
    summary.to_csv(TAB_DIR / "f3_complexity_response.csv", index=False)
    bins.to_csv(TAB_DIR / "f3_complexity_bins.csv", index=False)
    partial.to_csv(TAB_DIR / "f3_complexity_partial.csv", index=False)
