def _agent_action_rate(d: pd.DataFrame) -> np.ndarray:
    if "p_action" in d:
        return d["p_action"].to_numpy(float)
    return d["s"].to_numpy(float) / d["n"].to_numpy(float)


def _boot_pearson(x: np.ndarray, y: np.ndarray) -> tuple[float, float, float]:
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    ok = np.isfinite(x) & np.isfinite(y)
    x = x[ok]
    y = y[ok]
    if len(x) < 5 or np.std(x) <= 1e-10 or np.std(y) <= 1e-10:
        return np.nan, np.nan, np.nan
    r = float(pearsonr(x, y)[0])
    rng = np.random.default_rng(SEED)
    vals = []
    for _ in range(N_BOOT):
        idx = rng.integers(0, len(x), size=len(x))
        if np.std(x[idx]) <= 1e-10 or np.std(y[idx]) <= 1e-10:
            continue
        vals.append(float(pearsonr(x[idx], y[idx])[0]))
    if not vals:
        return r, np.nan, np.nan
    lo, hi = np.percentile(vals, [2.5, 97.5])
    return r, float(lo), float(hi)


