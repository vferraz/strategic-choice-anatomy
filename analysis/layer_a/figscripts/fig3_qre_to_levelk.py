def _ne_p1_act0(vec8) -> float:
    """P1 act0-probability under the standard NE selection.

    unique pure -> 0/1; unique mixed -> interior; 2-pure+mixed -> risk-dominant
    (fallback payoff-dominant -> mixed coordinate -> 0.5). Always returns a finite
    probability in [0,1]; the trembling-hand floor is applied by the caller.
    """
    p1, p2 = EQ.matrices_from_8vec(vec8)
    pairs, kind = EQ.enumerate_nash(p1, p2)
    if not pairs:
        return 0.5
    pure = [pr for pr in pairs if pr[0] in (0.0, 1.0) and pr[1] in (0.0, 1.0)]
    mixed = [pr for pr in pairs if pr not in pure]
    if len(pairs) == 1:
        return float(pairs[0][0])
    # multiple equilibria: try risk-dominant, then payoff-dominant, then mixed, then 0.5
    pne = EQ.pure_nash_equilibria(p1, p2)
    rd = EQ.risk_dominant_ne(pne, p1, p2)
    if rd is not None:
        return float(_action_to_act0prob(rd[0]) if rd[0] in (0, 1) else rd[0])
    pd_ne = EQ.payoff_dominant_ne(pne, p1, p2)
    if pd_ne is not None:
        return float(_action_to_act0prob(pd_ne[0]) if pd_ne[0] in (0, 1) else pd_ne[0])
    if mixed:
        return float(mixed[0][0])
    return 0.5


def ne_pred(df: pd.DataFrame) -> np.ndarray:
    """NE prediction on the CANONICAL axis, made finite with a fixed tremble."""
    out = np.empty(len(df))
    for i, (vec, canon) in enumerate(zip(df["vec8"], df["canon"])):
        p_act0 = _ne_p1_act0(vec)
        p_can = _flip_to_canonical(p_act0, int(canon))
        out[i] = (1.0 - 2.0 * NE_TREMBLE) * p_can + NE_TREMBLE
    return _clip(out)


# ---------------------------------------------------------------------------
# Vectorized payoff geometry. ``delta1``/``delta2`` (from oneshot_common) are the
# single source of truth for the scalar incentive gaps; here we vectorize the SAME
# algebra over a whole stack of games so the QRE/CH fixed points (called thousands
# of times inside the optimizer + bootstrap) never re-parse a vector per iteration.
# A 256-entry cache keyed on the frame's vec8-list object identity avoids rebuilding
# the stack on every predict() call. The vectorized gaps are asserted equal to the
# scalar delta1/delta2 in __main__ (see _selfcheck_vectorization).
# ---------------------------------------------------------------------------
_STACK_CACHE: dict[int, tuple] = {}


def _payoff_stack(df: pd.DataFrame) -> tuple:
    """Return (U1, U2, canon) with U1,U2 shape (G,2,2) for the frame's vec8 column.

    U1[g,i,j] = P1 payoff (row i, col j); U2 likewise. delta1(vec,q) ==
    q*U1[:,0,0]+(1-q)*U1[:,0,1] - (q*U1[:,1,0]+(1-q)*U1[:,1,1]); delta2(vec,q) ==
    q*U2[:,0,0]+(1-q)*U2[:,1,0] - (q*U2[:,0,1]+(1-q)*U2[:,1,1]).
    """
    key = id(df["vec8"].values)
    hit = _STACK_CACHE.get(key)
    if hit is not None and hit[0].shape[0] == len(df):
        return hit
    V = np.asarray([list(v) for v in df["vec8"]], dtype=float)   # (G,8)
    U1 = V[:, :4].reshape(-1, 2, 2)
    U2 = V[:, 4:].reshape(-1, 2, 2)
    canon = df["canon"].to_numpy(int)
    res = (U1, U2, canon)
    if len(_STACK_CACHE) > 256:
        _STACK_CACHE.clear()
    _STACK_CACHE[key] = res
    return res


def _vdelta1(U1: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Vectorized EU1(act0)-EU1(act1) over a stack; q is a length-G array."""
    return (q * U1[:, 0, 0] + (1 - q) * U1[:, 0, 1]
            - (q * U1[:, 1, 0] + (1 - q) * U1[:, 1, 1]))


def _vdelta2(U2: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Vectorized EU2(act0)-EU2(act1) over a stack; q is a length-G array."""
    return (q * U2[:, 0, 0] + (1 - q) * U2[:, 1, 0]
            - (q * U2[:, 0, 1] + (1 - q) * U2[:, 1, 1]))


def qre_pred(df: pd.DataFrame, lam: float, n_iter: int = 200, damp: float = 0.5,
             tol: float = 1e-9) -> np.ndarray:
    """QRE prediction on the canonical axis (vectorized fixed point over all games)."""
    U1, U2, canon = _payoff_stack(df)
    G = U1.shape[0]
    s1 = np.full(G, 0.5)
    s2 = np.full(G, 0.5)
    for _ in range(n_iter):
        n1 = expit(lam * _vdelta1(U1, s2))
        n2 = expit(lam * _vdelta2(U2, s1))
        ns1 = (1 - damp) * s1 + damp * n1
        ns2 = (1 - damp) * s2 + damp * n2
        if np.max(np.abs(ns1 - s1)) < tol and np.max(np.abs(ns2 - s2)) < tol:
            s1, s2 = ns1, ns2
            break
        s1, s2 = ns1, ns2
    p_can = np.where(canon == 0, s1, 1.0 - s1)
    return _clip(p_can)


def ch_pred(df: pd.DataFrame, tau: float, lam: float | None,
            kmax: int = CH_KMAX) -> np.ndarray:
    """Cognitive-hierarchy prediction on the canonical axis (vectorized over games).

    Levels k=0..kmax with Poisson weights pi_k ~ e^{-tau} tau^k / k!. Level k (>=1)
    responds to the NORMALIZED mixture of all lower levels 0..k-1. P1 and P2 ladders
    advance in lockstep. lam is None -> sharp best response (CH); else quantal at lam
    (QCH). Returns P1's act0-prob under the Poisson-weighted mixture, flipped to the
    canonical axis.
    """
    U1, U2, canon = _payoff_stack(df)
    G = U1.shape[0]
    w = _poisson_weights(tau, kmax)                  # (kmax+1,)
    a1 = np.empty((kmax + 1, G))
    a2 = np.empty((kmax + 1, G))
    a1[0] = 0.5
    a2[0] = 0.5
    for k in range(1, kmax + 1):
        wl = w[:k]
        wl = wl / wl.sum() if wl.sum() > 0 else np.full(k, 1.0 / k)
        q_for_p1 = wl @ a2[:k]                        # belief about P2 act0  (G,)
        q_for_p2 = wl @ a1[:k]                        # belief about P1 act0  (G,)
        d1 = _vdelta1(U1, q_for_p1)
        d2 = _vdelta2(U2, q_for_p2)
        if lam is None:
            a1[k] = np.where(d1 > 0, 1.0, np.where(d1 < 0, 0.0, 0.5))
            a2[k] = np.where(d2 > 0, 1.0, np.where(d2 < 0, 0.0, 0.5))
        else:
            a1[k] = expit(lam * d1)
            a2[k] = expit(lam * d2)
    p_act0 = w @ a1                                   # (G,)
    p_can = np.where(canon == 0, p_act0, 1.0 - p_act0)
    return _clip(p_can)


def _poisson_weights(tau: float, kmax: int = CH_KMAX) -> np.ndarray:
    ks = np.arange(kmax + 1)
    fact = np.array([math.factorial(int(k)) for k in ks], dtype=float)
    with np.errstate(over="ignore"):
        w = np.exp(-tau) * np.power(float(tau), ks) / fact
    tot = w.sum()
    return w / tot if tot > 0 else np.full(kmax + 1, 1.0 / (kmax + 1))


def _gap_sharp(gap: float) -> float:
    """Sharp best-response indicator on a canonical-signed gap (0.5 on exact tie)."""
    if gap > 0:
        return 1.0
    if gap < 0:
        return 0.0
    return 0.5


def lk_pred(df: pd.DataFrame, pi: np.ndarray) -> np.ndarray:
    """Level-k mixture (sharp best responses), pi over {L1,L2,L3}. Canonical axis.

    gap_Lk are already canonical-signed (positive favours the canonical action), so
    P_k^sharp = 1[gap_k>0] is already on the canonical axis -- no flip needed.
    """
    P = np.zeros(len(df))
    for w, b in zip(pi, LEVELS):
        g = df[f"gap_{b}"].to_numpy(float)
        Pk = np.where(g > 0, 1.0, np.where(g < 0, 0.0, 0.5))
        P += w * Pk
    return _clip(P)


def qlk_pred(df: pd.DataFrame, pi4: np.ndarray, lam: float) -> np.ndarray:
    """Quantal level-k: pi over {L0,L1,L2,L3}, shared precision lambda. Canonical axis.

    pi0 * 0.5 + sum_{k in L1,L2,L3} pi_k * Lambda(lam * gap_k).
    """
    P = pi4[0] * 0.5
    for w, b in zip(pi4[1:], LEVELS):
        P = P + w * expit(lam * df[f"gap_{b}"].to_numpy(float))
    return _clip(P)


# ===========================================================================
#  Binomial MLE fitting (shared core + per-model parameterizations)
# ===========================================================================
def _nll(p: np.ndarray, s: np.ndarray, n: np.ndarray) -> float:
    p = _clip(p)
    return float(-np.sum(s * np.log(p) + (n - s) * np.log(1.0 - p)))


def _softmax_simplex(theta: np.ndarray) -> np.ndarray:
    """Map free params (len k-1) to a length-k simplex via softmax with an anchor 0."""
    z = np.concatenate([[0.0], theta])
    z = z - z.max()
    e = np.exp(z)
    return e / e.sum()


def _fit_restarts(fun, x0_list, bounds=None):
    """L-BFGS-B with several restarts; return best (x, fun)."""
    best_x, best_f = None, np.inf
    for x0 in x0_list:
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                r = minimize(fun, np.asarray(x0, float), method="L-BFGS-B",
                             bounds=bounds, options={"maxiter": 500})
            if np.isfinite(r.fun) and r.fun < best_f:
                best_f, best_x = float(r.fun), np.asarray(r.x, float)
        except Exception:
            continue
    return best_x, best_f


def fit_model(name: str, df: pd.DataFrame) -> dict:
    """Fit one behavioural model by binomial MLE on df. Returns a param dict with a
    ``predict`` closure (callable on any frame with the same geometry columns)."""
    s = df["s"].to_numpy(float)
    n = df["n"].to_numpy(float)
    rng = np.random.default_rng(SEED)

    if name == "L0":
        return {"name": name, "params": {}, "predict": lambda d: _clip(np.full(len(d), 0.5))}

    if name == "NE":
        return {"name": name, "params": {}, "predict": ne_pred}

    if name == "QRE":
        def f(th):
            lam = th[0]
            return _nll(qre_pred(df, lam), s, n)
        x, _ = _fit_restarts(f, [[0.5], [0.1], [1.0], [2.0]], bounds=[(0.0, 50.0)])
        lam = float(x[0]) if x is not None else np.nan
        return {"name": name, "params": {"lambda": lam},
                "predict": lambda d, lam=lam: qre_pred(d, lam)}

    if name == "Lk":
        def f(th):
            pi = _softmax_simplex(th)            # 2 free -> 3-simplex over L1,L2,L3
            return _nll(lk_pred(df, pi), s, n)
        starts = [[0.0, 0.0]] + [list(v) for v in rng.normal(0, 1.0, size=(4, 2))]
        x, _ = _fit_restarts(f, starts)
        pi = _softmax_simplex(x) if x is not None else np.full(3, 1 / 3)
        return {"name": name, "params": {"pi_L1": pi[0], "pi_L2": pi[1], "pi_L3": pi[2]},
                "predict": lambda d, pi=pi: lk_pred(d, pi)}

    if name == "QLk":
        def f(th):
            pi = _softmax_simplex(th[:3])        # 3 free -> 4-simplex over L0,L1,L2,L3
            lam = th[3]
            return _nll(qlk_pred(df, pi, lam), s, n)
        starts = ([[0, 0, 0, 0.5], [0, 0, 0, 1.0], [0, 0, 0, 0.1]]
                  + [list(v) + [abs(g)] for v, g in
                     zip(rng.normal(0, 1.0, size=(4, 3)), rng.uniform(0.1, 2.0, 4))])
        x, _ = _fit_restarts(
            f, starts, bounds=[(-8, 8), (-8, 8), (-8, 8), (0.0, 50.0)])
        if x is not None:
            pi = _softmax_simplex(x[:3]); lam = float(x[3])
        else:
            pi = np.full(4, 0.25); lam = np.nan
        return {"name": name,
                "params": {"pi_L0": pi[0], "pi_L1": pi[1], "pi_L2": pi[2],
                           "pi_L3": pi[3], "lambda": lam},
                "predict": lambda d, pi=pi, lam=lam: qlk_pred(d, pi, lam)}

    if name == "CH":
        def f(th):
            return _nll(ch_pred(df, th[0], None), s, n)
        x, _ = _fit_restarts(f, [[1.0], [0.5], [1.5], [2.5]], bounds=[(0.0, 10.0)])
        tau = float(x[0]) if x is not None else np.nan
        return {"name": name, "params": {"tau": tau},
                "predict": lambda d, tau=tau: ch_pred(d, tau, None)}

    if name == "QCH":
        def f(th):
            tau, lam = th
            return _nll(ch_pred(df, tau, lam), s, n)
        starts = [[1.0, 0.5], [0.5, 1.0], [1.5, 0.2], [2.0, 1.0], [0.8, 2.0]]
        x, _ = _fit_restarts(f, starts, bounds=[(0.0, 10.0), (0.0, 50.0)])
        if x is not None:
            tau, lam = float(x[0]), float(x[1])
        else:
            tau = lam = np.nan
        return {"name": name, "params": {"tau": tau, "lambda": lam},
                "predict": lambda d, tau=tau, lam=lam: ch_pred(d, tau, lam)}

    raise ValueError(name)


# ===========================================================================
#  Panel (b): leave-GAMES-out CV predictive log-loss
# ===========================================================================
def cv_logloss(df: pd.DataFrame) -> dict[str, np.ndarray]:
    """Per model: per-game out-of-fold log-loss array (len = n_games), aligned to a
    pre-sorted game order so bootstrap resampling is deterministic.

    L0 and NE are parameter-free, so their OOF prediction equals their in-sample
    prediction (no fitting); we still pass each game through the standard binomial
    log-loss for a comparable bar.
    """
    df = df.sort_values("game_code").reset_index(drop=True)
    games = df["game_code"].to_numpy()
    gkf = GroupKFold(n_splits=min(10, df["game_code"].nunique()))
    ll = {m: np.full(len(df), np.nan) for m in MODEL_ORDER}

    for tr_idx, te_idx in gkf.split(df, groups=games):
        tr = df.iloc[tr_idx]
        te = df.iloc[te_idx]
        s_te = te["s"].to_numpy(float)
        n_te = te["n"].to_numpy(float)
        for m in MODEL_ORDER:
            fit = fit_model(m, tr)
            p = fit["predict"](te)
            p = _clip(p)
            # per-game normalized log-loss: -[s log p + (n-s) log(1-p)] / n
            ll[m][te_idx] = -(s_te * np.log(p) + (n_te - s_te) * np.log(1.0 - p)) / n_te
    return ll


def boot_logloss_ci(ll_arr: np.ndarray, n_boot: int = N_BOOT, seed: int = SEED):
    """Bootstrap-by-game CI on the mean of stored per-game OOF log-loss (no refit)."""
    v = ll_arr[np.isfinite(ll_arr)]
    if v.size == 0:
        return np.nan, np.nan, np.nan
    rng = np.random.default_rng(seed)
    means = v[rng.integers(0, v.size, size=(n_boot, v.size))].mean(1)
    return float(v.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def build_model_selection_cv(
    agent_games: dict[str, pd.DataFrame],
) -> tuple[pd.DataFrame, dict[str, dict[str, tuple[float, float, float]]]]:
    """Run the canonical leave-games-out comparison and persist its estimands.

    Models are refit within each of ten ``GroupKFold`` training partitions, with
    ``game_code`` as the held-out group.  The interval is a percentile bootstrap
    over the 144 stored out-of-fold per-game log losses; models are not refit
    inside that descriptive game-composition bootstrap.
    """
    rows = []
    cv_full: dict[str, dict[str, tuple[float, float, float]]] = {}
    for agent in AGENTS:
        d = agent_games[agent]
        losses = cv_logloss(d)
        n_games = int(d["game_code"].nunique())
        n_splits = min(10, n_games)
        cv_full[agent] = {}
        for model in MODEL_ORDER:
            mean, lo, hi = boot_logloss_ci(losses[model])
            cv_full[agent][model] = (mean, lo, hi)
            rows.append({
                "agent": agent,
                "display": DISPLAY[agent],
                "model": model,
                "n_params": N_PARAMS[model],
                "mean_logloss": mean,
                "ci_lo": lo,
                "ci_hi": hi,
                "n_games": n_games,
                "n_observations": int(d["n"].sum()),
                "n_splits": n_splits,
                "cv_group": "game_code",
                "ci_method": (
                    f"percentile bootstrap of stored OOF per-game losses; "
                    f"n_boot={N_BOOT}; no bootstrap refit"
                ),
            })
        best = min(MODEL_ORDER, key=lambda model: cv_full[agent][model][0])
        summary = " ".join(
            f"{model}={cv_full[agent][model][0]:.3f}" for model in MODEL_ORDER
        )
        print(f"  [{agent:18s}] best={best:3s} | {summary}")

    table = pd.DataFrame(rows)
    table.to_csv(TAB_DIR / "f3_model_selection_cv.csv", index=False)
    return table, cv_full


