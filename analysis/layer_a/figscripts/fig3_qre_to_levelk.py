def _qlk_arrays(df: pd.DataFrame) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return binomial counts and canonical-signed QLk gaps for one agent."""
    s = df["s"].to_numpy(float)
    n = df["n"].to_numpy(float)
    G = df[["gap_L1", "gap_L2", "gap_L3"]].to_numpy(float)
    if not (np.all(np.isfinite(s)) and np.all(np.isfinite(n)) and np.all(np.isfinite(G))):
        raise AssertionError("non-finite QLk fingerprint inputs")
    return s, n, G


def _qlk_pcanon_array(pi: np.ndarray, lam: float, G: np.ndarray) -> np.ndarray:
    return _clip(pi[0] * 0.5
                 + pi[1] * expit(lam * G[:, 0])
                 + pi[2] * expit(lam * G[:, 1])
                 + pi[3] * expit(lam * G[:, 2]))


def fit_qlk_sharpness(s: np.ndarray, n: np.ndarray, G: np.ndarray,
                      multi: bool = False) -> dict[str, float]:
    """Fit QLk on arrays and report depth plus probability-scale sharpness.

    This is the same QLk model family as ``fit_model("QLk", ...)`` but avoids
    DataFrame overhead inside the bootstrap used for panel b.
    """
    starts = [[0, 0, 0, 1.0]]
    if multi:
        starts += [[0, 0, 0, 0.3], [0.5, 0.5, 0.5, 2.0],
                   [-0.5, 0.7, 0.7, 2.0], [0.0, -0.7, 1.1, 2.5]]

    def f(th):
        pi = _softmax_simplex(np.asarray(th[:3], float))
        p = _qlk_pcanon_array(pi, float(th[3]), G)
        return _nll(p, s, n)

    x, _ = _fit_restarts(f, starts, bounds=[(-8, 8), (-8, 8), (-8, 8), (0.0, 50.0)])
    if x is None:
        pi = np.full(4, 0.25)
        lam = np.nan
        p = np.full(len(s), 0.5)
    else:
        pi = _softmax_simplex(x[:3])
        lam = float(x[3])
        p = _qlk_pcanon_array(pi, lam, G)
    return {
        "depth_pi": float(sum(k * pi[k] for k in range(4))),
        "sharpness": float(np.mean(np.maximum(p, 1.0 - p))),
        "lambda_QLk": lam,
        "pi_L0": float(pi[0]), "pi_L1": float(pi[1]),
        "pi_L2": float(pi[2]), "pi_L3": float(pi[3]),
        "lambda_QLk_boundary": bool(np.isfinite(lam) and lam >= 49.0),
    }


def boot_qlk_sharpness(s: np.ndarray, n: np.ndarray, G: np.ndarray,
                       n_boot: int = N_BOOT_FINGERPRINT, seed: int = SEED) -> dict[str, tuple[float, float]]:
    """Bootstrap-by-game CIs for the QLk depth/sharpness panel."""
    rng = np.random.default_rng(seed + 11)
    vals: dict[str, list[float]] = {"depth_pi": [], "sharpness": [], "lambda_QLk": []}
    for _ in range(n_boot):
        idx = rng.integers(0, len(s), size=len(s))
        try:
            fp = fit_qlk_sharpness(s[idx], n[idx], G[idx], multi=False)
        except Exception:
            continue
        for key in vals:
            v = fp[key]
            if np.isfinite(v):
                vals[key].append(float(v))

    out = {}
    for key, arr in vals.items():
        a = np.asarray(arr, float)
        if a.size:
            out[key] = (float(np.percentile(a, 2.5)), float(np.percentile(a, 97.5)))
        else:
            out[key] = (np.nan, np.nan)
    return out


def qlk_landmarks(df: pd.DataFrame) -> dict[str, float]:
    """Deterministic pure-level sharpness references over the same game set."""
    out = {"L0": 0.5}
    for level in LEVELS:
        g = df[f"gap_{level}"].to_numpy(float)
        p = expit(1e6 * g)
        out[level] = float(np.mean(np.maximum(p, 1.0 - p)))
    return out


def build_fingerprint_table(agent_games: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rows = []
    for ag in AGENTS:
        s, n, G = _qlk_arrays(agent_games[ag])
        fp = fit_qlk_sharpness(s, n, G, multi=True)
        ci = boot_qlk_sharpness(s, n, G)
        rows.append({
            "agent": ag,
            "display": DISPLAY[ag],
            **fp,
            "depth_pi_ci_lo": ci["depth_pi"][0],
            "depth_pi_ci_hi": ci["depth_pi"][1],
            "sharpness_ci_lo": ci["sharpness"][0],
            "sharpness_ci_hi": ci["sharpness"][1],
            "lambda_QLk_ci_lo": ci["lambda_QLk"][0],
            "lambda_QLk_ci_hi": ci["lambda_QLk"][1],
            "n_games": int(agent_games[ag]["game_code"].nunique()),
            "ci_method": f"bootstrap by game, n={N_BOOT_FINGERPRINT}; panel y is mean modal-action probability",
        })
    out = pd.DataFrame(rows)
    out.to_csv(TAB_DIR / "f3_fingerprint.csv", index=False)
    return out


