def qlk_depth(params: dict) -> float:
    """QLk mean reasoning level Sum_k k * pi_k over k = 0..3."""
    pis = [params.get(f"pi_L{k}", np.nan) for k in range(4)]
    if any(np.isnan(p) for p in pis):
        return np.nan
    return float(sum(k * p for k, p in enumerate(pis)))


def fit_fingerprint(df: pd.DataFrame) -> dict:
    """Full-sample QLk + CH + QCH fits -> depth/precision fingerprint for one agent."""
    qlk = fit_model("QLk", df)["params"]
    ch = fit_model("CH", df)["params"]
    qch = fit_model("QCH", df)["params"]
    return {
        "tau_CH": ch.get("tau", np.nan),
        "tau_QCH": qch.get("tau", np.nan),
        "lambda_QCH": qch.get("lambda", np.nan),
        "depth_pi": qlk_depth(qlk),
        "lambda_QLk": qlk.get("lambda", np.nan),
        "pi_L0": qlk.get("pi_L0", np.nan), "pi_L1": qlk.get("pi_L1", np.nan),
        "pi_L2": qlk.get("pi_L2", np.nan), "pi_L3": qlk.get("pi_L3", np.nan),
    }


def boot_fingerprint(df: pd.DataFrame, n_boot: int = N_BOOT_FINGERPRINT, seed: int = SEED):
    """Bootstrap-by-game CI on (depth_pi, lambda_QLk, tau_QCH) by refitting on
    resampled games. Returns dict of (lo, hi) per quantity."""
    df = df.reset_index(drop=True)
    games = df["game_code"].unique()
    idx_by_g = {g: np.where(df["game_code"].to_numpy() == g)[0] for g in games}
    rng = np.random.default_rng(seed + 7)
    depth, lam, tau = [], [], []
    for _ in range(n_boot):
        pick = rng.choice(games, size=len(games), replace=True)
        ii = np.concatenate([idx_by_g[g] for g in pick])
        sub = df.iloc[ii].reset_index(drop=True)
        try:
            qlk = fit_model("QLk", sub)["params"]
            qch = fit_model("QCH", sub)["params"]
            d = qlk_depth(qlk)
            if np.isfinite(d):
                depth.append(d)
            if np.isfinite(qlk.get("lambda", np.nan)):
                lam.append(qlk["lambda"])
            if np.isfinite(qch.get("tau", np.nan)):
                tau.append(qch["tau"])
        except Exception:
            continue

    def _ci(a):
        a = np.asarray(a, float)
        return (float(np.percentile(a, 2.5)), float(np.percentile(a, 97.5))) if a.size else (np.nan, np.nan)

    return {"depth_pi": _ci(depth), "lambda_QLk": _ci(lam), "tau_QCH": _ci(tau)}


