def griffiths_cardinal_lambda() -> pd.DataFrame:
    """Soft lambda for Griffiths on its OWN cardinal payoff axis.

    Rank-clean Griffiths subset from unified_pairs (sample=='griffiths'). The
    incentive gap is delta1c on the CARDINAL matrix (matrix_8vec) at q=0.5, oriented
    to the canonical action. This is a SEPARATE-AXIS robustness object: it must never
    be plotted on the same lambda bar as the ordinal rank agents.
    """
    up = pd.read_parquet(UNIFIED)
    up = up.loc[:, ~up.columns.duplicated()]
    g = up[up["sample"] == "griffiths"].copy()
    if g.empty:
        return pd.DataFrame([{"agent": "griffiths", "axis": "cardinal",
                              "lam_soft": np.nan, "ci_lo": np.nan, "ci_hi": np.nan,
                              "n_games": 0, "note": "no griffiths rows"}])

    def _vec(x):
        import json
        return [float(v) for v in (json.loads(x) if isinstance(x, str) else list(x))]

    g["vec8"] = [_vec(v) for v in g["matrix_8vec"]]
    g["canon"] = g["canonical_action_p1"].astype(int)
    g["delta1c"] = [canonical_sign(delta1(v, 0.5), int(c))
                    for v, c in zip(g["vec8"], g["canon"])]
    # canonical-aligned realized rate (realized_p1 is positional act0 rate)
    g["y_canon"] = [_flip_to_canonical(p, int(c))
                    for p, c in zip(g["realized_p1"].to_numpy(float), g["canon"])]
    # collapse to per-canonical-game means (game_code) so the unit is the game
    grp = g.groupby("game_code").agg(delta1c=("delta1c", "mean"),
                                     y_canon=("y_canon", "mean")).reset_index()
    x = grp["delta1c"].to_numpy(float)
    y = grp["y_canon"].to_numpy(float)
    lam, alpha = fit_lambda(x, y, "soft")
    lo, hi = boot_cluster_lambda(x, y, grp["game_code"].to_numpy(), "soft", n_boot=N_BOOT)
    return pd.DataFrame([{
        "agent": "griffiths", "axis": "cardinal (separate from rank lambda bar)",
        "lam_soft": lam, "alpha_soft": alpha, "ci_lo": lo, "ci_hi": hi,
        "n_games": int(len(grp)), "n_rows": int(len(g)),
        "note": "Griffiths cardinal-payoff robustness; do NOT compare to ordinal rank lambda",
    }])


