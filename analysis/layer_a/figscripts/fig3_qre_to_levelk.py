def _selfcheck_vectorization(agent_games) -> None:
    """Assert the vectorized gaps reproduce the scalar delta1/delta2 (single source
    of truth from oneshot_common) on a sample of games + beliefs."""
    d = agent_games["qwen"]
    U1, U2, _ = _payoff_stack(d)
    rng = np.random.default_rng(0)
    for q in [0.0, 0.25, 0.5, 0.73, 1.0]:
        qa = np.full(U1.shape[0], q)
        v1 = _vdelta1(U1, qa)
        v2 = _vdelta2(U2, qa)
        s1 = np.array([delta1(v, q) for v in d["vec8"]])
        s2 = np.array([delta2(v, q) for v in d["vec8"]])
        assert np.allclose(v1, s1, atol=1e-9), f"vdelta1 mismatch at q={q}"
        assert np.allclose(v2, s2, atol=1e-9), f"vdelta2 mismatch at q={q}"
    print("  [selfcheck] vectorized delta1/delta2 == scalar oneshot_common (OK)")


